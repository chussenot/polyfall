#!/usr/bin/env python3
"""Compiles the Polyfall arrangement (ARR-SPEC.yaml, in words) into sonomorph `.score` files.

The scores next to this file are generated: change the music here, run
`python3 audio/compose.py`, and commit both. The output is deterministic (fixed seed).

One beat is one eighth-note pulse. A bar is 12 pulses, always split 3 + 4 + 5:
the three piece sizes of the game, filling the 12 columns of the well.
"""
import random
from pathlib import Path

OUT = Path(__file__).parent
BAR = 12
BARS = 29  # the length of the theme (see FORM)

# The theme runs at 208 pulses a minute, give or take 0.02%. The game's mixer works in blocks of
# 4096 samples at 44100 Hz, and it only loops a sound cleanly when the loop is a whole number of
# blocks: otherwise the first notes of each pass are played early, on top of the last bar, and
# leave a hole behind them. So the tempo is the one, nearest to 208, at which 29 bars last
# exactly 1081 blocks.
RATE, BLOCK = 44100, 4096
BLOCKS = round(BARS * BAR * 60 / 208 * RATE / BLOCK)
TEMPO = BARS * BAR * 60 * RATE / (BLOCKS * BLOCK)  # 207.9618: a bar lasts 3.46 s
MS = TEMPO / 60000.0  # one millisecond, in beats

NOTES = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def midi(name):
    """'F#4' -> 66. Middle C is C4 = 60."""
    pc = NOTES[name[0]]
    rest = name[1:]
    while rest[0] in "#b":
        pc += 1 if rest[0] == "#" else -1
        rest = rest[1:]
    return 12 * (int(rest) + 1) + pc


# Each chord: the three notes of the low cell, the four of the middle cell, the five of the high
# cell, the bass note, and a three-note pad voicing.
CHORDS = {
    "Dm9":    ("D2 A2 D3",   "F3 A3 C4 A3",   "E5 A5 F5 C6 A5",   "D2", "D3 F3 C4"),
    "Fmaj7":  ("F2 C3 F3",   "A3 C4 E4 C4",   "E5 A5 G5 C6 A5",   "F2", "F3 A3 E4"),
    "G":      ("G2 D3 G3",   "B3 D4 G4 D4",   "D5 G5 B5 D6 B5",   "G2", "G3 B3 D4"),
    "Am7":    ("A2 E3 A3",   "C4 E4 G4 E4",   "E5 G5 C6 E6 C6",   "A2", "A3 C4 G4"),
    "Bbmaj7": ("Bb2 F3 Bb3", "D4 F4 A4 F4",   "D5 F5 A5 D6 A5",   "Bb1", "Bb3 D4 A4"),
    "C":      ("C3 G3 C4",   "E4 G4 C5 G4",   "D5 G5 E5 C6 G5",   "C2", "C4 E4 G4"),
    "Ebmaj7": ("Eb2 Bb2 Eb3", "G3 Bb3 D4 Bb3", "D5 G5 Bb5 D6 Bb5", "Eb2", "Eb3 G3 D4"),
    "A":      ("A2 E3 A3",   "D4 E4 G4 C#4",  "E5 A5 G5 C#6 E6",  "A1", "A3 D4 E4"),
    "C/E":    ("E2 C3 E3",   "G3 C4 E4 C4",   "D5 G5 E5 C6 G5",   "E2", "E3 G3 C4"),
    "Gm6":    ("G2 D3 G3",   "Bb3 D4 E4 D4",  "D5 G5 Bb5 E6 Bb5", "G2", "G3 Bb3 E4"),
}

# The form. 29 bars, about 100 s, and it loops: the peak falls back into the bare opening.
FORM = [
    ("A",  ["Dm9", "Dm9", "Fmaj7", "G", "Dm9", "Dm9", "Am7", "G"]),
    ("B",  ["Bbmaj7", "C", "Am7", "Bbmaj7", "Ebmaj7", "A"]),
    ("A2", ["Dm9", "Fmaj7", "G", "Dm9", "Am7", "G"]),
    ("BR", ["Dm9", "Bbmaj7", "Gm6"]),
    ("C",  ["Dm9", "Fmaj7", "C/E", "G", "Bbmaj7", "A"]),
]

# Melodies, one bar each: (pitch, pulses), "-" is a rest. Every bar is 3 + 4 + 5 pulses.
M1 = "D4:1 A4:1 G4:1  F4:2 E4:1 D4:1  C4:1 D4:4"        # the motif: up a fifth, down by step, turn, land
M2 = "D4:1 A4:1 C5:1  B4:2 A4:1 G4:1  A4:5"             # its answer, with the Dorian B natural
MELODY = {
    "A": [None, None, None, None,
          M1, M2,
          "E4:1 B4:1 A4:1  G4:2 F4:1 E4:1  D4:1 E4:4",   # the motif a step up
          "D4:1 B4:1 A4:1  G4:2 A4:1 B4:1  D5:5"],
    # B: only the three-note head of the motif, climbing; the rest of each bar is left open
    "B": ["F4:1 D5:1 C5:1  -:4  A4:5",
          "G4:1 E5:1 D5:1  -:4  C5:5",
          "A4:1 E5:1 D5:1  -:4  C5:2 B4:3",
          "Bb4:1 F5:1 E5:1  -:4  D5:5",
          "Bb4:1 G5:1 F5:1  D5:2 Bb4:1 G4:1  F4:5",
          "A4:1 E5:1 D5:1  C#5:2 D5:1 E5:1  E5:5"],
    "A2": [M1,
           "C4:1 A4:1 G4:1  F4:2 E4:1 C4:1  E4:1 F4:4",
           "D4:1 B4:1 A4:1  G4:2 A4:1 B4:1  A4:1 G4:4",
           M2,
           "E4:1 C5:1 B4:1  A4:2 G4:1 E4:1  G4:5",
           "G4:1 D5:1 B4:1  A4:2 B4:1 D5:1  E5:5"],
    # the break: the motif at half speed, across two bars, then nothing
    "BR": ["D4:2 A4:2 G4:2 F4:4 E4:2", "D4:2 C4:2 D4:8", None],
    "C": ["D5:1 A5:1 G5:1  F5:2 E5:1 D5:1  C5:1 D5:4",
          "C5:1 A5:1 G5:1  F5:2 E5:1 C5:1  E5:1 F5:4",
          "E5:1 C6:1 B5:1  G5:2 E5:1 D5:1  C5:1 E5:4",
          "D5:1 B5:1 A5:1  G5:2 A5:1 B5:1  D6:5",
          "F5:1 D6:1 C6:1  A5:2 Bb5:1 D6:1  F5:5",
          "E5:1 A5:1 G5:1  F5:2 E5:1 D5:1  C#5:1 E5:4"],
}

LEVEL_UP_TRIM = 2.8  # dB on the cue's master: set so the rendered file peaks near -3 dBFS

TRIMS = {
    "synth_bass": -7, "electronic_pulse": -4, "electronic_metal": 11,
    "brass_horns": 4, "strings_high": 4, "synth_lead": 2,
    "synth_pad": -11, "electronic_drone": -12, "strings_low_pizz": 5,
}

HEADER = """score 1
title {title}
# Generated by audio/compose.py from audio/ARR-SPEC.yaml. Do not edit: change compose.py.
tempo 0 {tempo}
length {length}
{loop}
seed 12
include @library/instruments/desk.inc
include @library/instruments/orchestra.inc
include @library/instruments/electronic.inc
"""


class Score:
    def __init__(self, seed):
        self.rng = random.Random(seed)
        self.lines = []

    def note(self, beat, dur, inst, pitch, vel, late_ms=0.0, loose_ms=0.0, wobble=5):
        """One note. `late_ms` moves the whole part off the grid; `loose_ms` is the player's own spread."""
        t = beat + (late_ms + self.rng.uniform(-loose_ms, loose_ms)) * MS
        v = max(1, min(127, round(vel + self.rng.uniform(-wobble, wobble))))
        p = pitch if isinstance(pitch, str) else str(pitch)
        self.lines.append((max(0.0, t), f"note {max(0.0, t):.3f} {dur:.3f} {inst} {p} {v}"))

    def raw(self, beat, text):
        self.lines.append((beat, text))

    def text(self):
        return "\n".join(line for _, line in sorted(self.lines, key=lambda x: x[0])) + "\n"


def parse(bar):
    out, at = [], 0.0
    for tok in bar.split():
        pitch, dur = tok.split(":")
        if pitch != "-":
            out.append((at, float(dur), pitch))
        at += float(dur)
    assert at == BAR, (bar, at)
    return out


def theme():
    s = Score(7)
    bars = [(sec, i, ch) for sec, chords in FORM for i, ch in enumerate(chords)]
    assert len(bars) == BARS
    # How loud each section plays (0..1). It falls twice: into the break, and at the loop.
    level = {"A": 0.8, "B": 0.78, "A2": 0.85, "BR": 0.5, "C": 1.0}
    for n, (sec, i, ch) in enumerate(bars):
        t0 = n * BAR
        low, mid, high, (bass,), pad = (x.split() for x in CHORDS[ch])
        lv = level[sec]
        full = sec in ("A2", "C") or (sec == "A" and i >= 4) or sec == "B"

        # --- the three cells: 3 low plucks, 4 middle bow strokes, 5 high glass notes ---
        for k, p in enumerate(low):
            s.note(t0 + k, 0.9, "strings_low_pizz", p, (96, 74, 82)[k] * (0.75 + 0.25 * lv),
                   late_ms=7, loose_ms=5)
        if sec == "C":  # the basses join the low cell at the peak
            s.note(t0, 0.9, "strings_bass_spic", max(midi(low[0]) - 12, 26), 96, late_ms=7, loose_ms=4)
        if not (sec == "A" and i < 2) and sec != "BR":
            for k, p in enumerate(mid):
                s.note(t0 + 3 + k, 0.5, "strings_mid_spic", p, (88, 66, 76, 64)[k] * (0.7 + 0.3 * lv),
                       loose_ms=6)
        if (sec == "A" and i >= 4) or sec in ("A2", "C") or (sec == "B" and i >= 4):
            for k, p in enumerate(high):
                s.note(t0 + 7 + k, 0.6, "synth_glass", p, (84, 64, 70, 78, 60)[k] * (0.7 + 0.3 * lv),
                       late_ms=-6, loose_ms=3)
                if sec in ("A", "A2"):  # plucked violins shadow the glass an octave down, then leave
                    s.note(t0 + 7 + k, 0.5, "strings_high_pizz", midi(p) - 12, 58, late_ms=4, loose_ms=7)

        # --- the hook: three ticks, on the first pulse of each cell ---
        if not (sec == "BR" and i > 0):
            for at, v in ((0, 92), (3, 62), (7, 76)):
                s.note(t0 + at, 0.1, "electronic_metal", "C6", v * (0.6 + 0.4 * lv), wobble=3)
        if sec == "C":  # and at the peak, a quiet tick on every pulse
            for k in range(BAR):
                if k not in (0, 3, 7):
                    s.note(t0 + k, 0.08, "electronic_metal", "C6", 34, wobble=6)

        # --- bass ---
        if full:
            s.note(t0, 2.6, "synth_bass", bass, 100 * (0.7 + 0.3 * lv), wobble=3)
            if sec in ("A2", "C"):
                s.note(t0 + 7, 1.2, "synth_bass", bass, 84, wobble=3)
            if sec == "C":
                s.note(t0 + 3, 0.8, "synth_bass", midi(bass) + 12, 78, wobble=3)
                s.note(t0 + 10, 0.8, "synth_bass", midi(bass) + 12, 70, wobble=3)
        if sec in ("A2", "C"):  # a soft kick under the first and last cell
            s.note(t0, 0.5, "electronic_pulse", "A1", 104 if sec == "C" else 86, wobble=2)
            if sec == "C":
                s.note(t0 + 7, 0.5, "electronic_pulse", "A1", 88, wobble=2)

        # --- pads: bowed strings in B and at the peak, the synth pad alone in the break ---
        if sec in ("B", "C"):
            for p, inst in zip(pad, ("strings_low", "strings_mid", "strings_mid")):
                s.note(t0, BAR, inst, p, 52 if sec == "B" else 70, wobble=3)
        if sec == "BR":
            for p in pad:
                s.note(t0, BAR, "synth_pad", p, 70, wobble=2)
            if i == 0:
                s.note(t0, 3 * BAR, "electronic_drone", "D2", 80, wobble=0)

        # --- melody ---
        line = MELODY[sec][i]
        if line:
            for at, dur, p in parse(line):
                if sec == "A":
                    s.note(t0 + at, dur * 0.95, "brass_horns", p, 80, late_ms=12, loose_ms=6)
                elif sec == "B":
                    s.note(t0 + at, dur * 0.95, "strings_high", p, 80 + 3 * i, late_ms=10, loose_ms=6)
                elif sec == "A2":
                    s.note(t0 + at, dur * 0.95, "strings_high", midi(p) + 12, 88, late_ms=10, loose_ms=6)
                    s.note(t0 + at, dur * 0.95, "brass_horns", p, 70, late_ms=14, loose_ms=6)
                elif sec == "BR":
                    s.note(t0 + at, dur * 0.97, "brass_horns", p, 60, late_ms=18, loose_ms=8)
                else:
                    s.note(t0 + at, dur * 0.95, "strings_high", p, 94, late_ms=8, loose_ms=5)
                    s.note(t0 + at, dur * 0.95, "brass_horns", midi(p) - 12, 84, late_ms=12, loose_ms=5)
                    s.note(t0 + at, dur * 0.95, "synth_lead", p, 60, late_ms=8, loose_ms=3)

    # --- fills and joins: bars 8, 14, 23 and 29, so never a fill every four bars ---
    def bar(n):  # 1-based bar number -> beat
        return (n - 1) * BAR
    for k, p in enumerate(("D5", "E5", "F5", "G5", "A5")):  # end of A: the high cell runs up into B
        s.note(bar(8) + 7 + k, 0.5, "strings_high_spic", p, 70 + 4 * k, loose_ms=5)
    s.note(bar(14) + 7, 5, "timpani_roll", "A2", 70)        # end of B: a roll on the dominant
    s.note(bar(15), 2, "timpani", "D3", 96)
    s.note(bar(23) + 2, 10, "percussion", 53, 76)           # end of the break: a cymbal swells
    s.note(bar(23) + 7, 5, "timpani_roll", "A2", 84)
    s.note(bar(24), 2, "timpani", "D3", 116)
    s.note(bar(24), 6, "percussion", 49, 92)
    for k, p in enumerate(("A4", "C#5", "E5", "G5", "A5")):  # end of C: the dominant, then the drop
        s.note(bar(29) + 7 + k, 0.5, "strings_high_spic", p, 96 - 6 * k, loose_ms=5)
    # the peak thins out over its last bar so the loop's bare opening is not a cliff
    # (automation is relative: decibels added to the gain the library gives each instrument)
    s.raw(bar(29) + 6, f"ramp electronic.gain {bar(29) + 6} {bar(29) + 12} 0 -6 smooth")
    s.raw(0, "ramp electronic.gain 0 2 -6 0 smooth")

    # --- the balance, measured on the render: the melody in front, the ticks audible, the bass
    # under both. One constant trim per instrument, held for the whole loop. ---
    for inst, trim in TRIMS.items():
        s.raw(0, f"ramp {inst}.gain 0 0.01 {trim} {trim}")

    length = len(bars) * BAR
    head = HEADER.format(title="Polyfall: theme (gameplay loop)", tempo=TEMPO, length=length, loop="loop on")
    (OUT / "theme.score").write_text(head + s.text())
    return length


def level_up():
    """The level rises. The three cells run upward once, six times faster than in the theme
    (the game has just sped up), into an open chord that hangs.

    It plays over the theme, at whatever bar the player happens to be in, so it obeys two rules.
    It uses only D, E and A: no third, so it cannot be major against a minor bar or the reverse.
    And it has no pulse of its own: twelve notes in half a second are a gesture, not a rhythm,
    so they cannot fall out of step with the theme's count.

    It starts a quarter of a second late. A level only rises on a row clear, and the clear is
    heard first."""
    s = Score(3)
    beat = TEMPO / 60.0                      # beats in one second
    start, step = 0.25, 0.042                # seconds
    run = [("strings_low_pizz", p, 92) for p in ("D3", "A3", "D4")]
    run += [("strings_mid_spic", p, 86) for p in ("E4", "A4", "D5", "E5")]
    run += [("synth_glass", p, 82) for p in ("A5", "D6", "E6", "A6", "D7")]
    for k, (inst, p, vel) in enumerate(run):
        s.note((start + step * k) * beat, 0.6 * beat, inst, p, vel + 2 * k, loose_ms=2)
    land = start + step * len(run)           # 0.754 s: the chord arrives as the run ends
    # horns and strings are slow to speak, so they are asked for a little early
    for p, vel in (("D3", 100), ("A3", 96), ("E4", 92)):
        s.note(land * beat, 1.3 * beat, "brass_horns", p, vel, late_ms=-60, wobble=2)
    for inst, p, vel in (("strings_low", "D3", 88), ("strings_mid", "A3", 80), ("strings_mid", "E4", 78)):
        s.note(land * beat, 1.7 * beat, inst, p, vel, late_ms=-80, wobble=2)
    for p, vel in (("D5", 76), ("A5", 72), ("E6", 66)):
        s.note(land * beat, 0.9 * beat, "synth_glass", p, vel, wobble=2)
    # a breath of air under the first quarter second, so the cue does not begin with silence
    s.note(0, 0.9 * beat, "electronic_air", "C5", 80)
    s.raw(0, f"ramp electronic_air.gain 0 {land * beat:.3f} -8 4 smooth")
    s.raw(land * beat, f"ramp electronic_air.gain {land * beat:.3f} {(land + 0.5) * beat:.3f} 4 -30 smooth")
    s.raw(0, f"ramp master.gain 0 0.01 {LEVEL_UP_TRIM} {LEVEL_UP_TRIM}")
    head = HEADER.format(title="Polyfall: level up", tempo=TEMPO, length=round(2.7 * beat, 2), loop="tail 1.6")
    (OUT / "level_up.score").write_text(head + s.text())


def game_over():
    """The motif once more, slower and lower, landing on an open fifth: neither major nor minor."""
    s = Score(5)
    line = [("A3", 0, 3), ("G3", 3, 4), ("F3", 7, 2), ("E3", 9, 2), ("D3", 11, 1),
            ("C3", 12, 2), ("D3", 14, 10)]
    for p, at, dur in line:
        s.note(at, dur * 0.97, "strings_low", p, 80, late_ms=10, loose_ms=6)
        s.note(at, dur * 0.97, "brass_horns", p, 58, late_ms=16, loose_ms=6)
    for p, at, dur in (("D2", 0, 7), ("Bb1", 7, 5), ("Eb2", 12, 2), ("D2", 14, 10)):
        s.note(at, dur, "strings_bass", p, 76, late_ms=8, wobble=3)
    for p in ("A3", "E4"):
        s.note(14, 10, "strings_mid", p, 56, wobble=3)
    for k, p in enumerate(("D2", "A2", "D3")):  # the low cell, one last time
        s.note(14 + k, 0.9, "strings_low_pizz", p, 80 - 8 * k, late_ms=8, loose_ms=4)
    s.note(21, 1.5, "synth_glass", "E6", 54)
    s.note(14, 3, "timpani", "D3", 62)
    s.raw(0, "ramp master.gain 0 0.01 5 5")
    head = HEADER.format(title="Polyfall: game over", tempo=150, length=24, loop="tail 4")
    (OUT / "game_over.score").write_text(head + s.text())


# The title theme: the same cells and harmony, a quarter slower, with room between the notes.
# Its loop obeys the same mixer rule as the theme's: 10 bars at the tempo, nearest to 156, at
# which they last a whole number of blocks.
TITLE_BARS = 10
TITLE_BLOCKS = round(TITLE_BARS * BAR * 60 / 156 * RATE / BLOCK)
TITLE_TEMPO = TITLE_BARS * BAR * 60 * RATE / (TITLE_BLOCKS * BLOCK)

TITLE_FORM = ["Dm9", "Dm9", "Bbmaj7", "Fmaj7", "Dm9", "Am7", "Bbmaj7", "G", "Gm6", "Am7"]
# The motif, stretched: only its head and its landing, with the middle of the bar left open.
TITLE_MELODY = [
    None,
    "D4:1 A4:1 G4:1  F4:4  -:5",
    "F4:1 D5:1 C5:1  -:4  A4:5",
    "C4:1 A4:1 G4:1  F4:2 E4:2  -:5",
    "D4:1 A4:1 C5:1  B4:4  A4:5",
    "E4:1 C5:1 B4:1  -:4  G4:2 A4:3",
    "Bb4:1 F5:1 E5:1  D5:4  -:5",
    "D4:1 B4:1 A4:1  G4:4  -:5",
    "G4:1 D5:1 Bb4:1  A4:4  -:5",
    None,
]


def title():
    """The title screen: an invitation, not the game's drive. The low cell counts every bar, the
    other two cells come and go, a horn says the motif's head and the strings hold the chord.
    No bass, no kick; the last bar breathes on Am7 and its pad rings into the top of the loop."""
    s = Score(11)
    for n, ch in enumerate(TITLE_FORM):
        t0 = n * BAR
        low, mid, high, (bass,), pad = (x.split() for x in CHORDS[ch])
        for k, p in enumerate(low):  # the count of three, softly, every bar
            s.note(t0 + k, 1.4, "strings_low_pizz", p, (80, 58, 64)[k], late_ms=7, loose_ms=5)
        if n % 2 == 1:  # the middle cell every other bar, the glass on the bars between
            for k, p in enumerate(mid):
                s.note(t0 + 3 + k, 0.6, "strings_mid_spic", p, (66, 50, 58, 48)[k], loose_ms=6)
        elif n > 0:
            for k, p in enumerate(high):
                s.note(t0 + 7 + k, 1.2, "synth_glass", p, (66, 50, 56, 62, 48)[k], late_ms=-6, loose_ms=3)
        s.note(t0, 0.1, "electronic_metal", "C6", 54, wobble=3)  # one tick: the bar begins
        for p, inst in zip(pad, ("strings_low", "strings_mid", "strings_mid")):
            s.note(t0, BAR + 1, inst, p, 50, wobble=3)
        s.note(t0, BAR, "strings_bass", bass, 52, late_ms=8, wobble=3)
        line = TITLE_MELODY[n]
        if line:
            for at, dur, p in parse(line):
                s.note(t0 + at, dur * 0.97, "brass_horns", p, 66, late_ms=14, loose_ms=6)
                if n >= 4:
                    s.note(t0 + at, dur * 0.97, "strings_high", midi(p) + 12, 56, late_ms=10, loose_ms=6)
    s.note(0, TITLE_BARS * BAR, "electronic_drone", "D2", 60, wobble=0)
    for inst, trim in TRIMS.items():
        s.raw(0, f"ramp {inst}.gain 0 0.01 {trim} {trim}")
    s.raw(0, f"ramp master.gain 0 0.01 {TITLE_TRIM} {TITLE_TRIM}")
    length = TITLE_BARS * BAR
    head = HEADER.format(title="Polyfall: title", tempo=TITLE_TEMPO, length=length, loop="loop on")
    (OUT / "title.score").write_text(head + s.text())
    return length


TITLE_TRIM = 5  # dB on the title's master: set so the rendered file peaks near -3 dBFS


if __name__ == "__main__":
    beats = theme()
    level_up()
    game_over()
    tb = title()
    print(f"title: {tb} beats, {tb / TITLE_TEMPO * 60:.1f} s, {TITLE_BLOCKS} blocks")
    print(f"theme: {beats} beats, {beats / TEMPO * 60:.1f} s")
