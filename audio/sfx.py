#!/usr/bin/env python3
"""Polyfall's sound effects, as code: writes one sonomorph `.score` per cue into audio/sfx/.

The scores are generated: change a sound here, run `python3 audio/sfx.py`, then
`mise run audio` to render them, and commit all three (this file, the scores, the .ogg files).
The output is deterministic (fixed seeds).

Two materials, so the ear can tell what kind of thing happened:

  contact  dry, short, unpitched or low: what the piece physically does
           (step sideways, turn, bump, run down, settle, slam)
  glass    a struck-bar tone, tuned: what the rules do
           (rows clear, pause, resume, new game)

Every tuned note is a D, an E or an A. Those three sit over every chord of the theme, so a
cue never sounds wrong against the bar it happens to land on.

Times are in seconds (tempo 60, one beat a second). Each cue starts at its first sample:
the mixer already adds its own delay, so a file must not add more.
"""
import random
from pathlib import Path

OUT = Path(__file__).parent / "sfx"

NOTES = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def midi(name):
    """'A5' -> 81. Middle C is C4 = 60."""
    return 12 * (int(name[-1]) + 1) + NOTES[name[0]]


# Final level of each cue, in dB on its master. Set from measurement (see audio/README.md):
# each cue is rendered, its loudest 100 ms is measured, and this number is moved until the cue
# sits where the cue sheet says it should. Change a sound's character above; its level here.
TRIM = {
    "move_left": 3.3, "move_right": 3.6, "rotate": -3.6, "blocked": -18.4,
    "soft_drop": 7.6, "lock": -6.7, "hard_drop": -10.3, "clear_1": -2.4,
    "clear_2": -4.6, "clear_3": -4.9, "clear_4": -11.0, "clear_5": -11.1,
    "pause": -1.5, "resume": -1.1, "new_game": -2.8,
}


class Cue:
    """One score. Instruments are declared once each; notes are kept in time order."""

    def __init__(self, name, title, length, seed=1, loop=False):
        self.name, self.title, self.length, self.seed, self.loop = name, title, length, seed, loop
        self.insts, self.notes, self.auxes = {}, [], []

    def aux(self, line):
        self.auxes.append(line)

    def inst(self, name, patch):
        self.insts[name] = patch

    def note(self, at, dur, inst, pitch, vel):
        p = midi(pitch) if isinstance(pitch, str) else pitch
        self.notes.append((at, f"note {at:.4f} {dur:.4f} {inst} {p:g} {max(1, min(127, round(vel)))}"))

    def write(self):
        lines = [
            "score 1",
            f"title Polyfall: {self.title}",
            "# Generated by audio/sfx.py. Do not edit: change sfx.py.",
            "tempo 0 60",
            f"length {self.length:.12g}",
            "loop on" if self.loop else "tail 0",
            f"seed {self.seed}",
            f"master gain={TRIM[self.name]:g}",
        ]
        lines += self.auxes
        lines += [f"inst {name} {patch}" for name, patch in self.insts.items()]
        lines += [text for _, text in sorted(self.notes, key=lambda n: n[0])]
        OUT.mkdir(exist_ok=True)
        (OUT / f"{self.name}.score").write_text("\n".join(lines) + "\n")


# --- the glass voice -------------------------------------------------------------------
# A struck bar has partials at 1 : 2.76 : 5.40 of its pitch, each dying faster than the one
# below. Three sines at those ratios make a tone that reads as glass or ceramic, not as a
# synthesizer. `ring` is the time the fundamental takes to die away.
PARTIALS = ((0.0, 1.00, 1.0), (17.57, 0.30, 0.28), (29.20, 0.12, 0.10))  # semitones up, level, ring


def glass(cue, ring, send=""):
    for k, (_, _, share) in enumerate(PARTIALS):
        cue.inst(f"glass{k}", f"synth wave=sine attack=0.0008 decay={ring * share:.4f} sustain=0 "
                              f"release={ring * share:.4f} {send}".strip())


def ping(cue, at, pitch, vel, ring):
    base = midi(pitch) if isinstance(pitch, str) else pitch
    for k, (up, level, share) in enumerate(PARTIALS):
        cue.note(at, ring * share * 2.5, f"glass{k}", base + up, vel * level)


# --- contact ---------------------------------------------------------------------------

def move(name, side):
    """A detent: one tick as the piece steps a column. Left sits a little lower and to the
    left, right a little higher and to the right; held, the ticks become a ratchet."""
    c = Cue(name, f"move {'left' if side < 0 else 'right'}", 0.05)
    centre = 2000 if side < 0 else 2600
    pan = 0.3 * side
    c.inst("tick", f"synth gain=6 pan={pan:g} wave=noise filter=bp cutoff={centre} res=0.5 keytrack=0 "
                   "attack=0.0003 decay=0.011 sustain=0 release=0.008")
    # a trace of pitch under the noise, so the tick has a body and is not just hiss
    c.inst("body", f"synth pan={pan:g} wave=sine pitchenv=5 pitchtime=0.004 "
                   "attack=0.0003 decay=0.009 sustain=0 release=0.006")
    c.note(0, 0.03, "tick", "C4", 127)
    c.note(0, 0.03, "body", "D6" if side < 0 else "E6", 20)
    c.write()


def rotate():
    """A quarter turn: a click, then a tone that rises a fifth and stops dead. The rise is
    the turn; the clean stop is the piece landing on the grid."""
    c = Cue("rotate", "rotate", 0.09)
    c.inst("click", "synth wave=noise filter=hp cutoff=3200 res=0.2 keytrack=0 "
                    "attack=0.0002 decay=0.005 sustain=0 release=0.004")
    c.inst("turn", "synth wave=triangle pitchenv=-7 pitchtime=0.03 filter=lp cutoff=6000 keytrack=0 "
                   "attack=0.0006 decay=0.042 sustain=0 release=0.02")
    c.inst("turn2", "synth wave=sine pitchenv=-7 pitchtime=0.03 "
                    "attack=0.0006 decay=0.018 sustain=0 release=0.01")
    c.note(0, 0.02, "click", "C4", 50)
    c.note(0, 0.07, "turn", "A6", 100)     # 1760 Hz: above the theme's melody, so it need not be loud
    c.note(0, 0.04, "turn2", "A7", 34)     # the octave, shorter: gives the stop its edge
    c.write()


def blocked():
    """The move or the turn did not happen: a dull knock, low and short. It answers the key
    without rewarding it."""
    c = Cue("blocked", "blocked", 0.12)
    c.inst("knock", "synth wave=sine pitchenv=7 pitchtime=0.008 drive=0.25 "
                    "attack=0.0006 decay=0.045 sustain=0 release=0.03")
    c.inst("wood", "synth wave=triangle filter=lp cutoff=1100 keytrack=0 pitchenv=4 pitchtime=0.006 "
                   "attack=0.0006 decay=0.022 sustain=0 release=0.015")
    c.inst("thud", "synth gain=14 wave=noise filter=lp cutoff=520 res=0.2 keytrack=0 "
                   "attack=0.0005 decay=0.014 sustain=0 release=0.01")
    # the knock's body is under 200 Hz, which laptop speakers barely play: a short, dull tap
    # around 1.6 kHz carries it there, well under the move ticks so it does not read as one
    c.inst("tap", "synth gain=32 wave=noise filter=bp cutoff=1600 res=0.3 keytrack=0 "
                  "attack=0.0004 decay=0.008 sustain=0 release=0.006")
    c.note(0, 0.09, "knock", "D3", 112)
    c.note(0, 0.012, "tap", "C4", 96)
    c.note(0, 0.05, "wood", "D4", 104)
    c.note(0, 0.03, "thud", "C4", 110)
    c.write()


# The game's mixer works in blocks of 4096 samples at 44100 Hz. It loops a sound cleanly only
# if the loop is a whole number of blocks; otherwise each pass starts early and leaves a hole.
BLOCK_SECONDS = 4096 / 44100


def soft_drop():
    """Down is held: the piece runs down row by row. A loop of eight soft ticks, no two quite
    alike, four mixer blocks long (372 ms, a tick every 46 ms). It is the quietest sound in
    the game."""
    length = 4 * BLOCK_SECONDS
    c = Cue("soft_drop", "soft drop (loop)", length, loop=True)
    c.inst("run", "synth gain=8 wave=noise filter=bp cutoff=1250 res=0.45 keytrack=0 "
                  "attack=0.0004 decay=0.007 sustain=0 release=0.005")
    c.inst("run_body", "synth wave=sine attack=0.0004 decay=0.006 sustain=0 release=0.004")
    for k, vel in enumerate((104, 76, 92, 70, 98, 74, 88, 68)):
        c.note(0.004 + length / 8 * k, 0.02, "run", "C4", vel)
        c.note(0.004 + length / 8 * k, 0.02, "run_body", "D5", vel * 0.12)
    c.write()


def lock():
    """The piece becomes part of the stack: a wooden 'tok' with a low body. Present on every
    piece, so it is short and never bright."""
    c = Cue("lock", "lock", 0.16)
    c.inst("tok", "synth wave=sine pitchenv=12 pitchtime=0.007 drive=0.15 "
                  "attack=0.0005 decay=0.06 sustain=0 release=0.04")
    c.inst("tap", "synth gain=15 wave=noise filter=bp cutoff=1500 res=0.35 keytrack=0 "
                  "attack=0.0003 decay=0.010 sustain=0 release=0.008")
    c.inst("tok2", "synth wave=triangle filter=lp cutoff=1400 keytrack=0 pitchenv=7 pitchtime=0.005 "
                   "attack=0.0005 decay=0.03 sustain=0 release=0.02")
    c.note(0, 0.12, "tok", "G3", 90)       # 196 Hz: the weight, for speakers that can play it
    c.note(0, 0.05, "tok2", "G4", 104)     # 392 Hz: the same knock, for those that cannot
    c.note(0, 0.03, "tap", "C4", 104)
    c.write()


def hard_drop():
    """The extra a hard drop adds on top of `lock`: a thump that falls to a low D, the air it
    pushes out, and a crack at the first instant. The game scales it with the distance fallen."""
    c = Cue("hard_drop", "hard drop", 0.34)
    c.inst("thump", "synth wave=sine pitchenv=19 pitchtime=0.03 drive=0.4 "
                    "attack=0.0006 decay=0.15 sustain=0 release=0.06")
    c.inst("punch", "synth gain=4 wave=triangle filter=lp cutoff=700 keytrack=0 pitchenv=12 pitchtime=0.02 "
                    "attack=0.0006 decay=0.07 sustain=0 release=0.03")
    c.inst("air", "synth gain=7 wave=noise filter=lp cutoff=700 res=0.1 keytrack=0 fenv=3.2 fattack=0.0005 "
                  "fdecay=0.045 fsustain=0 attack=0.0005 decay=0.08 sustain=0 release=0.04")
    c.inst("crack", "synth gain=11 wave=noise filter=bp cutoff=2800 res=0.3 keytrack=0 "
                    "attack=0.0002 decay=0.007 sustain=0 release=0.005")
    c.note(0, 0.26, "thump", "D2", 96)
    c.note(0, 0.12, "punch", "D3", 110)
    c.note(0, 0.14, "air", "C4", 100)
    c.note(0, 0.02, "crack", "C4", 96)
    c.write()


# --- glass -----------------------------------------------------------------------------

COUNT = ("D5", "A5", "D6", "E6", "A6")   # one ping per row cleared, always from the bottom up


def clear(rows):
    """Rows clear. One ping per row, climbing in fifths and fourths, so the count can be heard.
    Around the pings: the sweep that crosses the row, the fragments it breaks into, and a low
    thud when the stack above lands. Four and five rows add a held chord and a longer room."""
    n = rows
    length = (0.6, 0.7, 0.85, 1.6, 2.1)[n - 1]
    ring = (0.20, 0.23, 0.26, 0.42, 0.52)[n - 1]
    big = n >= 4
    c = Cue(f"clear_{n}", f"clear {n} row{'s' if n > 1 else ''}", length, seed=10 + n)
    if big:
        c.aux(f"aux space reverb preset=hall rt60={1.3 if n == 4 else 1.8} gain=-2")
    else:
        c.aux("aux space reverb preset=room gain=-4")
    wet = (-15, -14, -12, -9, -8)[n - 1]
    glass(c, ring, f"send=space:{wet}")
    c.inst("sweep", "synth gain=9 wave=noise filter=bp cutoff=900 res=0.4 keytrack=0 fenv=3 fattack=0.10 "
                    "fdecay=0.05 fsustain=0.6 attack=0.012 decay=0.11 sustain=0 release=0.05 "
                    f"send=space:{wet - 4}")
    c.inst("glint", "synth gain=3 wave=sine attack=0.0005 decay=0.016 sustain=0 release=0.012 "
                    f"spread=0 send=space:{wet - 2}")
    c.inst("settle", "synth wave=sine pitchenv=9 pitchtime=0.018 drive=0.2 "
                     "attack=0.002 decay=0.10 sustain=0 release=0.05")

    # the sweep: light running along the row
    c.note(0, 0.16, "sweep", "C4", (58, 68, 78, 94, 104)[n - 1])
    # the count
    for k, pitch in enumerate(COUNT[:n]):
        ping(c, 0.012 + 0.042 * k, pitch, 84 + 7 * k, ring)
    # the fragments: short high sines, scattered over the time the cells break up
    rng = random.Random(40 + n)
    spread = 0.06 + 0.042 * n
    for _ in range((3, 6, 9, 16, 22)[n - 1]):
        at = 0.07 + rng.uniform(0, spread + 0.08)
        c.note(at, 0.03, "glint", rng.choice(("D7", "E7", "A7", "A6", "D8")), rng.uniform(26, 58))
    # the stack above comes down: 0.27 s is when the nearest rows land on screen
    c.note(0.27, 0.16, "settle", "D2", (44, 56, 68, 86, 98)[n - 1])
    if big:
        # the reward: an open chord (no third, so it fits any bar) that swells and hangs
        c.inst("bloom", "synth wave=triangle stack=4 detune=9 spread=0.8 filter=lp cutoff=2400 "
                        f"keytrack=0.3 attack=0.05 decay={0.7 if n == 4 else 1.0} sustain=0 "
                        "release=0.5 send=space:-6")
        for pitch, vel in (("D4", 62), ("A4", 56), ("E5", 50)) + ((("D3", 60),) if n == 5 else ()):
            c.note(0.012 + 0.042 * (n - 1), length - 0.5, "bloom", pitch, vel + (8 if n == 5 else 0))
        if n == 5:
            ping(c, 0.012 + 0.042 * n + 0.03, "D7", 70, ring)   # a last one above the count
    c.write()


def ui(name, title, pitches, gap, ring, vel=78):
    """Pause, resume, new game: two or three pings. Down for stop, up for go."""
    c = Cue(name, title, 0.03 + gap * len(pitches) + ring * 1.6)
    c.aux("aux space reverb preset=room gain=-5")
    glass(c, ring, "send=space:-13")
    for k, pitch in enumerate(pitches):
        ping(c, gap * k, pitch, vel + 5 * k, ring)
    c.write()


if __name__ == "__main__":
    move("move_left", -1)
    move("move_right", 1)
    rotate()
    blocked()
    soft_drop()
    lock()
    hard_drop()
    for rows in range(1, 6):
        clear(rows)
    ui("pause", "pause", ("A5", "E5"), 0.065, 0.11, vel=72)
    ui("resume", "resume", ("E5", "A5"), 0.065, 0.11, vel=72)
    ui("new_game", "new game", ("D5", "A5", "D6"), 0.05, 0.16)
    print(f"{len(TRIM)} scores in {OUT}")
